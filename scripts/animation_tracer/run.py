"""Regenerate the traced animations.

    python scripts/animation_tracer/run.py            # every animation in specs.py
    python scripts/animation_tracer/run.py 41,83      # only these

For each id it
  1. runs the program in specs.py and records one step per action (tracer.py)
  2. writes web_src/src/animations/trace/<id>.ts  (the animation reads it)
  3. updates every lesson block in docs/content/data.json with that animationId:
     steps = 預告 (what each action will do), results = 執行後 (what it left), caption
"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
sys.path.insert(0, HERE)
import specs
from tracer import Tracer

TRACE_DIR = os.path.join(ROOT, 'web_src', 'src', 'animations', 'trace')
DATA = os.path.join(ROOT, 'docs', 'content', 'data.json')


def trace(i):
    sp = specs.SPECS[i]
    src = sp['src'].strip('\n')
    notes = {}
    for key, txt in (sp.get('notes') or {}).items():
        at = src.find(key)
        assert at >= 0, f'{i}: note key not found in code: {key!r}'
        notes[src[:at].count('\n') + 1] = txt
    t = Tracer(src, env=dict(sp.get('env', {})), notes=notes, intro=sp['intro'], max_steps=600)
    t.calldesc = specs.CALLDESC
    specs.SPECS_STATE['g'] = t.g
    return dict(id=i, caption=sp['caption'], code=t.lines, steps=t.run())


def main():
    ids = [int(x) for x in sys.argv[1].split(',')] if len(sys.argv) > 1 else sorted(specs.SPECS)
    os.makedirs(TRACE_DIR, exist_ok=True)
    traces = {}
    for i in ids:
        d = trace(i)
        traces[i] = d
        with open(os.path.join(TRACE_DIR, f'{i}.ts'), 'w', encoding='utf-8') as f:
            f.write('// generated by scripts/animation_tracer/run.py — one step per action (operator, index, call, assignment, if/while/for)\n')
            f.write("import type { Trace } from '../../animation_kit/AlgoKit';\n")
            f.write('const T: Trace = ' + json.dumps(d, ensure_ascii=False) + ';\nexport default T;\n')
        print(f'{i}: {len(d["steps"])} steps')

    data = json.load(open(DATA, encoding='utf-8'))
    n = 0
    for m in data['modules']:
        for l in m['lessons']:
            for b in l['content']:
                if b.get('type') == 'animation' and b.get('animationId') in traces:
                    d = traces[b['animationId']]
                    b['caption'] = d['caption']
                    b['steps'] = ['還沒開始執行'] + [s['pre'] for s in d['steps'][1:]]
                    b['results'] = [s['post'] for s in d['steps']]
                    n += 1
    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    print(f'updated {n} lesson blocks in docs/content/data.json')


if __name__ == '__main__':
    main()
